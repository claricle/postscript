# frozen_string_literal: true

require "tmpdir"
require_relative "../../script/guide_operators"

RSpec.describe GuideOperators do
  let(:fixture_dir) { File.expand_path("../fixtures/guide", __dir__) }
  let(:commit) { "0123abc456def" }
  let(:expected) do
    {
      "abs" => { "categories" => %w[arithmetic-math font-text], "level" => 1 },
      "index" => { "categories" => ["arithmetic-math"], "level" => 1 },
      "setcolor" => { "categories" => [], "level" => 2 },
      "show" => { "categories" => %w[arithmetic-math font-text],
                  "level" => nil },
    }
  end
  let(:header) do
    "# Generated by script/guide_operators.rb from the " \
      "PostScript Language Guide.\n" \
      "# Do not edit. Regenerate: ruby script/guide_operators.rb " \
      "GUIDE_CHECKOUT\n"
  end

  it "extracts only references with unique categories and their first level" do
    operators = described_class.extract(fixture_dir)

    expect(operators).to eq(expected)
    expect(operators.keys).to eq(operators.keys.sort)
    expect(operators).to have_key("index")
    expect(operators).not_to have_key("psindex")
    expect(operators).not_to have_key("brackets")
  end

  it "writes the header and sorted operator metadata as YAML" do
    Dir.mktmpdir do |dir|
      path = File.join(dir, "operators.yml")
      described_class.write(fixture_dir, path, commit: commit)
      content = File.read(path)
      payload = YAML.safe_load(content)
      expect(content).to start_with(header)
      expect(payload).to eq(
        "guide" => { "repository" => "claricle/postscript-guide",
                     "commit" => commit },
        "operators" => expected,
      )
      expect(payload.fetch("operators").keys).to eq(expected.keys.sort)
    end
  end

  it "sorts operator keys supplied out of order" do
    yaml = described_class.to_yaml(expected.to_a.reverse.to_h, commit)

    expect(YAML.safe_load(yaml).fetch("operators").keys).to eq(expected.keys)
  end

  ["*Level 2* and later", "LEVEL 2 ONLY"].each do |statement|
    it "extracts #{statement} before a later level statement" do
      Dir.mktmpdir do |dir|
        references = File.join(dir, "docs", "commands", "references")
        FileUtils.mkdir_p(references)
        content = "---\nlayout: default\ntitle: test\n---\n" \
                  "= test\n#{statement}\nThis is a Level 1 operator.\n"
        File.write(File.join(references, "test.adoc"), content)

        expect(described_class.extract(dir)).to eq(
          "test" => { "categories" => [], "level" => 2 },
        )
      end
    end
  end

  ["= test\n", "---\nlayout: default\n---\n= test\n"].each do |content|
    it "rejects a reference without a front-matter title: #{content.inspect}" do
      Dir.mktmpdir do |dir|
        references = File.join(dir, "docs", "commands", "references")
        FileUtils.mkdir_p(references)
        File.write(File.join(references, "test.adoc"), content)

        expect { described_class.extract(dir) }
          .to raise_error(RuntimeError, /test\.adoc/)
      end
    end
  end
end
